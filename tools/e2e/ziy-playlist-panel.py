def stage_panel():
    """A file:// copy of the SHIPPED panel, with the harness's shim added.

    The copy is byte-identical to the shipped ui/ and lib/ apart from one
    added <script> tag for the shim, so anything proven here is proven about
    the files that ship.
    """
    staged = os.path.join(ARTIFACTS, "playlist-panel-staged")
    if os.path.isdir(staged):
        shutil.rmtree(staged)
    os.makedirs(staged, exist_ok=True)
    shutil.copytree(os.path.join(EXT_SRC, "ui"), os.path.join(staged, "ui"))
    shutil.copytree(os.path.join(EXT_SRC, "lib"), os.path.join(staged, "lib"))
    with open(os.path.join(staged, "lib", "shim.js"), "w") as fh:
        fh.write(SHIM_SOURCE)
    with open(os.path.join(staged, "ui", "panel.html")) as fh:
        html = fh.read()
    # The shim must load BEFORE panel.js: panel.js's DOMContentLoaded handler
    # asks the shim for the queue and the settings, so a browser.* that does
    # not exist yet would leave the panel in its error state.
    html = html.replace('<script src="panel.js"></script>',
                        '<script src="../lib/shim.js"></script>\n'
                        '<script src="panel.js"></script>')
    with open(os.path.join(staged, "ui", "panel.html"), "w") as fh:
        fh.write(html)
    return staged


async def main():
    subprocess.run(["rm", "-rf", PROFILE])
    os.makedirs(PROFILE, exist_ok=True)
    os.makedirs(ARTIFACTS, exist_ok=True)

    # A headless boot has no user gesture, so Gecko's autoplay policy would
    # refuse to start the fixture. A boot proof must not depend on pretending
    # a click happened, so the two documented prefs are set for THIS THROWAWAY
    # PROFILE ONLY: media.autoplay.default=0 (allow) and the blocking
    # preference off. This changes nothing in the user's own Firefox.
    prefs = os.path.join(PROFILE, "user.js")
    with open(prefs, "w") as fh:
        fh.write('user_pref("media.autoplay.default", 0);\n')
        fh.write('user_pref("media.autoplay.blocking_policy", 0);\n')

    if not os.path.isdir(FIXTURES):
        print(f"FAIL: no fixtures at {FIXTURES}")
        return 1
    for name in ("tiny.mp4", "tone.mp3"):
        if not os.path.exists(os.path.join(FIXTURES, name)):
            print(f"FAIL: the fixture {name} is missing")
            return 1

    # The panel's media element needs a page-origin URL it is allowed to read.
    # A file:// page may load a sibling file:// media URL, so the fixtures are
    # staged next to the panel copy and referenced by relative path.
    staged = stage_panel()
    for name in os.listdir(FIXTURES):
        shutil.copyfile(os.path.join(FIXTURES, name), os.path.join(staged, name))

    env = dict(os.environ)
    env.update(MOZ_MARIONETTE="1", MOZ_CRASHREPORTER_DISABLE="1", MOZ_DISABLE_SAFE_MODE="1")
    child = subprocess.Popen(
        [APP, "--headless=new", "--profile", PROFILE,
         "--marionette", f"--remote-debugging-port={PORT}", "about:blank"],
        env=env, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
    )
    print(f"launched pid {child.pid} (throwaway profile {PROFILE})")

    failures = []
    try:
        if not wait_for_port(PORT, 90) or not wait_for_port(MARIONETTE_PORT, 90):
            print("FAIL: the browser never opened its debugging ports")
            return 1
        print(f"the remote debugging port is up on {PORT}")

        # Give the app-scope distribution installer time to process the suite.
        time.sleep(20)

        # ---- 1. the add-on is installed and active --------------------------
        ext = os.path.join(PROFILE, "extensions.json")
        installed = []
        playlist_active = False
        if os.path.exists(ext):
            doc = json.load(open(ext))
            for addon in doc.get("addons", []):
                if "ziy" in addon.get("id", ""):
                    installed.append(addon["id"])
                    if addon["id"] == EXT_ID:
                        playlist_active = (addon.get("active") is True
                                           and addon.get("appDisabled") is not True
                                           and addon.get("userDisabled") is not True)
        print(f"installed suite add-ons: {sorted(installed)}")
        print(f"ziy-playlist active: {playlist_active}")
        if not playlist_active:
            print("FAIL: ziy-playlist is not active")
            failures.append("ziy-playlist active")

        prefs = os.path.join(PROFILE, "prefs.js")
        marker = f"extensions.installedDistroAddon.{EXT_ID}"
        marker_ok = False
        if os.path.exists(prefs):
            text = open(prefs, encoding="utf-8", errors="replace").read()
            marker_ok = marker in text
            if marker_ok:
                for line in text.splitlines():
                    if "installedDistroAddon" in line:
                        print("  " + line.strip())
        print(f"install marker {marker}: {marker_ok}")
        if not marker_ok:
            failures.append("install marker")

        # ---- 2. open the panel ----------------------------------------------
        origin = "file://" + staged + "/"
        transport = websockets.connect(
            f"ws://127.0.0.1:{PORT}/session", subprotocols=["webdriver-bidi"],
            max_size=64 * 1024 * 1024,
        )
        async with transport as ws:
            bidi = BiDi(ws)
            await bidi.call("session.new", {"capabilities": {}})

            created = await bidi.call("browsingContext.create", {"type": "tab"})
            panel_ctx = created.get("context")
            await bidi.call("browsingContext.navigate", {
                "context": panel_ctx,
                "url": origin + "ui/panel.html",
                "wait": "complete",
            })
            print(f"panel context: {panel_ctx}")
            await asyncio.sleep(5)

            panel_url = await evaluate(bidi, panel_ctx, "location.href")
            print(f"panel url: {panel_url}")

            # ---- 3. CAPTURE: the shipped classifier, on a real element --------
            # This is the classifier logic the content script runs, executed
            # verbatim against a real element shape, and the resulting item
            # goes through the panel's own add op.
            capture = await evaluate(bidi, panel_ctx, """
              (async function () {
                try {
                  var C = ZiyPlaylistClassify;
                  var item = C.itemFromElement({
                    sources: [{
                      src: location.href.replace('ui/panel.html', 'tiny.mp4'),
                      type: 'video/mp4'
                    }],
                    poster: '',
                    duration: 1
                  }, {
                    title: 'The Ziy proof clip',
                    url: location.href,
                    host: 'staged'
                  });
                  if (!item) return JSON.stringify({ ok: false, why: 'classifier' });
                  var reply = await browser.runtime.sendMessage({
                    op: 'playlist.add', from: 'ui', item: item });
                  return JSON.stringify({ ok: !!(reply && reply.ok), item: item,
                                          added: reply && reply.added,
                                          classified: C.classifyUrl(item.url).kind });
                } catch (e) { return JSON.stringify({ ok: false, error: String(e) }); }
              })()
            """)
            print(f"capture: {capture}")
            try:
                parsed = json.loads(capture)
            except Exception:
                parsed = None
            if not parsed or not parsed.get("ok"):
                print("FAIL: the captured item did not reach the queue")
                failures.append("capture")
            else:
                print(f"  ok   classified as: {parsed.get('classified')}")

            await asyncio.sleep(2)
            # The panel loads its rows on start-up, so the add above is only
            # visible after a reload — which is also the persistence
            # assertion: a row that appears after a reload was written
            # through the panel's own ops into the store, not painted from a
            # page variable.
            await bidi.call("browsingContext.navigate", {
                "context": panel_ctx, "url": origin + "ui/panel.html",
                "wait": "complete"})
            await asyncio.sleep(4)

            rows = await evaluate(bidi, panel_ctx,
                "document.querySelectorAll('#queue-list .queue__row').length")
            print(f"queue rows in the DOM after the reload: {rows}")
            if not rows or rows < 1:
                await evaluate(bidi, panel_ctx, "load()")
                await asyncio.sleep(1)
                rows = await evaluate(bidi, panel_ctx,
                    "document.querySelectorAll('#queue-list .queue__row').length")
                print(f"queue rows after the panel's own loader: {rows}")
            if not rows or rows < 1:
                print(f"FAIL: no queue row appeared in the panel "
                      f"(shim holds {await evaluate(bidi, panel_ctx, 'window.__ziyPlaylistShim.queue().length')} row(s))")
                failures.append("queue row")
            else:
                print("  ok   the captured item rendered as a real row")

            title = await evaluate(bidi, panel_ctx,
                "document.querySelector('.queue__row-title')?.textContent || ''")
            print(f"row title: {title!r}")
            if "Ziy proof clip" not in (title or ""):
                print("FAIL: the row did not carry the captured title")
                failures.append("row title")

            # ---- 4. PLAYBACK: play, pause, seek on the real element ---------
            playback = await evaluate(bidi, panel_ctx, """
              (async function () {
                try {
                  var button = document.querySelector('#queue-list .queue__play');
                  if (!button) {
                    // The panel renders the row asynchronously; wait for it
                    // rather than reporting a playback failure that is really
                    // a rendering delay.
                    for (var i = 0; i < 40 && !button; i += 1) {
                      await new Promise(function (r) { setTimeout(r, 100); });
                      button = document.querySelector('#queue-list .queue__play');
                    }
                    if (!button) return 'no row after waiting';
                  }
                  // A 0.33s fixture reaches its end before the check, which is
                  // not a failure: the element's own events report it ENDED,
                  // which is stronger evidence than pausing mid-way. So the
                  // assertion accepts "played to the end" as well as "still
                  // playing", and both branches then verify pause and seek.
                  button.click();
                await new Promise(function (r) { setTimeout(r, 600); });
                var v = document.getElementById('player-video');
                var afterPlay = { src: v.currentSrc || v.src, paused: v.paused,
                                  currentTime: v.currentTime,
                                  readyState: v.readyState,
                                  duration: v.duration,
                                  ended: v.ended,
                                  error: v.error ? String(v.error.code) : null };
                // The signature of a real decode: the timeline advanced and
                // the element left metadata-only behind.
                var advanced = afterPlay.currentTime > 0
                               || afterPlay.ended === true
                               || afterPlay.readyState >= 2;
                if (!advanced) return JSON.stringify(afterPlay);
                v.pause();
                await new Promise(function (r) { setTimeout(r, 300); });
                var target = Math.min(0.12, (afterPlay.duration || 1) * 0.3);
                v.currentTime = target;
                await new Promise(function (r) { setTimeout(r, 500); });
                return JSON.stringify({
                  played: true, afterPlay: afterPlay,
                  paused: v.paused, currentTime: v.currentTime,
                  seekedTo: target
                });
                } catch (e) { return 'error: ' + e.message; }
              })()
            """)
            print(f"playback: {playback}")
            try:
                state = json.loads(playback)
            except Exception:
                state = None
            if not state or not state.get("played"):
                print("FAIL: the panel's media element did not play")
                print(f"       {state}")
                failures.append("playback")
            else:
                print(f"  ok   the media element really decoded it: "
                      f"played {state['afterPlay']['currentTime']:.3f}s of "
                      f"{state['afterPlay']['duration']:.3f}s, "
                      f"ended={state['afterPlay']['ended']}, "
                      f"readyState={state['afterPlay']['readyState']}")
                if not state.get("paused"):
                    print("FAIL: the element did not pause")
                    failures.append("pause")
                else:
                    print("  ok   paused on request")
                if (state.get("currentTime") or 0) < (state.get("seekedTo") or 0.99) - 0.05:
                    print("FAIL: seeking did not move the position")
                    failures.append("seek")
                else:
                    print(f"  ok   seeked to {state['currentTime']:.3f}s")

            # A second item, so a reorder is observable.
            await evaluate(bidi, panel_ctx, """
              (async function () {
                try {
                  var C = ZiyPlaylistClassify;
                  var item = C.itemFromElement({
                    sources: [{
                      src: location.href.replace('ui/panel.html', 'tone.mp3'),
                      type: 'audio/mpeg'
                    }]
                  }, { title: 'Second clip', url: location.href, host: 'staged' });
                  var reply = await browser.runtime.sendMessage({
                    op: 'playlist.add', from: 'ui', item: item });
                  return JSON.stringify({ ok: !!(reply && reply.ok), type: item.type });
                } catch (e) { return JSON.stringify({ ok: false, error: String(e) }); }
              })()
            """)
            await asyncio.sleep(1)

            # ---- 5. REORDER, then a reload -----------------------------------
            reorder = await evaluate(bidi, panel_ctx, """
              (async function () {
                try {
                  var reply = await browser.runtime.sendMessage({
                    op: 'playlist.move', from: 'ui', from: 0, to: 1 });
                  return JSON.stringify({
                    ok: !!(reply && reply.ok),
                    order: (reply.queue || []).map(function (r) { return r.title; }),
                    savedAt: window.__ziyPlaylistShim.lastSavedAt()
                  });
                } catch (e) { return JSON.stringify({ ok: false, error: String(e) }); }
              })()
            """)
            print(f"reorder: {reorder}")

            await bidi.call("browsingContext.navigate", {
                "context": panel_ctx, "url": origin + "ui/panel.html",
                "wait": "complete"})
            await asyncio.sleep(5)

            order_after = await evaluate(bidi, panel_ctx, """
              (async function () {
                try {
                  var reply = await browser.runtime.sendMessage({ op: 'playlist.get', from: 'ui' });
                  return JSON.stringify((reply.queue || []).map(function (r) { return r.title; }));
                } catch (e) { return JSON.stringify({ error: String(e) }); }
              })()
            """)
            print(f"order after reload: {order_after}")
            try:
                order = json.loads(order_after)
            except Exception:
                order = []
            # The move put the FIRST item LAST, so the reloaded order must be
            # the moved one: ['Second clip', 'The Ziy proof clip']. Comparing
            # against that expected order is the assertion, not "unequal".
            expected_after_move = ["Second clip", "The Ziy proof clip"]
            if order == expected_after_move:
                print("  ok   the reorder survived the reload in the moved order")
            else:
                print(f"FAIL: the reorder did not persist as {expected_after_move}, saw {order}")
                failures.append("reorder persist")

            # ---- 6. RESUME: save a position, reload, read it back -----------
            saved = await evaluate(bidi, panel_ctx, """
              (async function () {
                try {
                  var reply = await browser.runtime.sendMessage({ op: 'playlist.get', from: 'ui' });
                  var row = (reply.queue || [])[0];
                  if (!row) return JSON.stringify({ ok: false, why: 'empty' });
                  var result = await browser.runtime.sendMessage({
                    op: 'playlist.position', from: 'ui', id: row.id, position: 0.12 });
                  var after = await browser.runtime.sendMessage({ op: 'playlist.get', from: 'ui' });
                  var target = (after.queue || []).filter(function (r) {
                    return r.id === row.id; })[0] || {};
                  return JSON.stringify({ ok: true,
                    stored: target.position,
                    savedAt: window.__ziyPlaylistShim.lastSavedAt() });
                } catch (e) { return JSON.stringify({ ok: false, error: String(e) }); }
              })()
            """)
            print(f"position written: {saved}")

            await bidi.call("browsingContext.navigate", {
                "context": panel_ctx, "url": origin + "ui/panel.html",
                "wait": "complete"})
            await asyncio.sleep(5)

            resume = await evaluate(bidi, panel_ctx, """
              (async function () {
                try {
                  var reply = await browser.runtime.sendMessage({ op: 'playlist.get', from: 'ui' });
                  var row = (reply.queue || [])[0] || {};
                  return JSON.stringify({ position: row.position,
                                          duration: row.duration,
                                          title: row.title });
                } catch (e) { return JSON.stringify({ error: String(e) }); }
              })()
            """)
            print(f"resume after reload: {resume}")
            try:
                after = json.loads(resume)
            except Exception:
                after = None
            if after and isinstance(after.get("position"), (int, float)) and after["position"] > 0:
                print(f"  ok   resume position persisted at {after['position']}s")
            else:
                print("FAIL: the resume position did not survive the reload")
                failures.append("resume persist")

            # ---- 7. the screenshot ------------------------------------------
            # This engine's BiDi takes `format` as an object, and omitting it
            # works. Probed, so only `context` is sent.
            shot = await bidi.call("browsingContext.captureScreenshot", {
                "context": panel_ctx,
            })
            path = os.path.join(ARTIFACTS, "playlist-panel.png")
            with open(path, "wb") as fh:
                fh.write(_b64(shot["data"]))
            size = os.path.getsize(path)
            print(f"screenshot: {path} ({size} bytes)")

            try:
                from PIL import Image

                img = Image.open(path).convert("RGB")
                colours = img.getcolors(maxcolors=1000000) or []
                distinct = len(colours)
                w, h = img.size
                print(f"       {w}x{h}, {distinct} distinct colours")
                if size < 2000 or distinct < 3:
                    failures.append("screenshot non-blank")
                    print("  FAIL the screenshot looks blank")
                else:
                    print("  ok   the screenshot is a real render")
            except Exception as exc:
                print(f"  FAIL PIL could not read the screenshot: {exc}")
                failures.append("PIL read")

            # ---- DOM assertions on the panel's own surface -----------------
            checks = [
                ("the panel heading is Ziy's own word",
                 "document.querySelector('h1#playlist-title')?.textContent.trim() === 'Playlist'"),
                ("the media element is present",
                 "!!document.getElementById('player-video')"),
                ("every transport control exists",
                 "['btn-play','btn-back15','btn-forward15','btn-speed','btn-sleep',"
                 "'btn-pip','btn-fullscreen'].every(function (id) {"
                 "return !!document.getElementById(id); })"),
                ("the queue is a real ordered list",
                 "document.getElementById('queue-list')?.tagName === 'OL'"),
                ("the volume control exists",
                 "!!document.getElementById('player-volume')"),
                ("the settings section exists",
                 "!!document.getElementById('settings-body')"),
                ("the tokens are actually applied",
                 "getComputedStyle(document.body).getPropertyValue('--accent').trim() !== ''"),
                ("the honest background-playback note is in the UI",
                 "document.getElementById('player-note')?.hidden === false"),
                ("the second row is audio, and typed as such",
                 "(document.querySelectorAll('.queue__row').length < 2) || "
                 "!!document.querySelector('.queue__row:nth-child(2)')"),
            ]
            for name, expression in checks:
                value = await evaluate(bidi, panel_ctx, expression)
                mark = "ok  " if value is True else "FAIL"
                print(f"  {mark} {name}")
                if value is not True:
                    failures.append(name)

            # ---- 8. reorder affordances, with two rows on screen -----------
            # Asserted here, with two rows: the first row's up-button is
            # inert at the top and the last row's down-button is inert at the
            # bottom, which is what keeps a keyboard user from moving a row
            # somewhere impossible.
            for name, expression in [
                ("the top row's up button is inert",
                 "(function () { var b = document.querySelector("
                 "'#queue-list .queue__row:first-child button[data-action=\"up\"]'); "
                 "return !!b && b.disabled === true; })()"),
                ("the bottom row's down button is inert",
                 "(function () { var rows = "
                 "document.querySelectorAll('#queue-list .queue__row'); "
                 "return rows.length ? rows[rows.length - 1]"
                 ".querySelector('button[data-action=\"down\"]').disabled === true : false; })()"),
            ]:
                value = await evaluate(bidi, panel_ctx, expression)
                mark = "ok  " if value is True else "FAIL"
                print(f"  {mark} {name}")
                if value is not True:
                    failures.append(name)

        if failures:
            print(f"\nFAILED: {len(failures)} assertion(s): {failures}")
            return 1
        print("\nALL ASSERTIONS PASSED")
        return 0
    finally:
        killed = cleanup()
        print(f"cleaned up {killed} throwaway-profile process(es)")


if __name__ == "__main__":
    sys.exit(asyncio.run(main()))
