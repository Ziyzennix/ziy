#!/usr/bin/env python3
"""Ziy Playlist — the panel proof, over WebDriver BiDi.

Proves, on a real headless Ziy boot with a throwaway profile:

  1. the ziy-playlist add-on is installed and active (extensions.json + the
     `extensions.installedDistroAddon` marker in prefs.js — the acceptance
     criterion)
  2. the panel page renders and its own DOM assertions pass, driven over BiDi
     (the same route the shields and talk workers proved on this machine)
  3. CAPTURE: the shipped lib/classify.js classifies a real media element's
     sources as addable, and the item lands in the queue through the
     extension's own message bus
  4. PLAYBACK: a real mp4 generated by gstreamer on this machine plays in the
     panel's real media element — play, pause, seek and the element's own
     events prove it, not a fake
  5. REORDER persists across a panel reload
  6. RESUME: the playback position persists across a panel reload
  7. a screenshot of the panel is non-blank, checked with PIL

Route and why this one. Firefox's remote protocol is Marionette/WebDriver BiDi
(firefox-source-docs.mozilla.org/remote/webdriver-bidi/Extensions.html), not
Chrome's CDP: `webExtension.moz:listExtensions` is not built into this engine
and extensions.json carries no moz-extension UUID, so the panel is reached as
a staged file:// copy of the SHIPPED files with a browser-API shim injected by
the harness. That is the same route tools/e2e/ziy-talk-panel.py uses and
replica/proofs-talk.md §4.4 records: a declared content script does not inject
on this engine build, for ANY ziy add-on (verified here: shields' cosmetic
script is absent from a launch page too), so the extension-page route cannot
be driven live. The install marker and the add-on's active state are still
proven from the real profile above, so this proves the SURFACE, not the
install — and it is stated as such rather than glossed.

The media element is the player, so step 4 drives the real thing: the same
ui/panel.js the extension ships, playing a real file the extension's own test
suite generated.

Kill hygiene (this is the part that must never break): every process this
script starts is matched by the anchored pattern /tmp/ziy-playlist-verify, and
only by that. The user's own Firefox and LibreOffice are never matched,
because the project directory name contains "brave".
"""

