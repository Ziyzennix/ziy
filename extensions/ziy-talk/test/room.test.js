test('valid ids pass and every malformed shape is rejected', () => {
  const good = ROOM.generateRoomId();
  const cases = {
    'a valid id': [good, true],
    'too short': [good.slice(0, 14), false],
    'too long': [good + 'a', false],
    'empty': ['', false],
    'whitespace only': ['   ', false],
    'a dash': [good.slice(0, 5) + '-' + good.slice(6), false],
    'a space': [good.slice(0, 5) + ' ' + good.slice(6), false],
    'a plus': [good.slice(0, 5) + '+' + good.slice(6), false],
    'an underscore': [good.slice(0, 5) + '_' + good.slice(6), false],
    'a slash': [good.slice(0, 5) + '/' + good.slice(6), false],
    'a colon': [good.slice(0, 5) + ':' + good.slice(6), false],
    'capital Ö': [good.slice(0, 5) + 'Ö' + good.slice(6), false],
    'a latin-1 high byte': [good.slice(0, 5) + '\u00ff' + good.slice(6), false],
    'a Cyrillic lookalike': [good.slice(0, 5) + '\u0430' + good.slice(6), false],
    'an emoji': [good.slice(0, 5) + '\u{1f600}' + good.slice(6), false],
    'a newline': [good.slice(0, 5) + '\n' + good.slice(6), false],
    'a null byte': [good.slice(0, 5) + '\u0000' + good.slice(6), false],
    'not a string': [null, false],
    'not a string either': [undefined, false],
    'a number': [123456789012345, false],
  };
  for (const [label, [value, expected]] of Object.entries(cases)) {
    assert.equal(ROOM.isValidRoomId(value), expected, label);
  }
  // A 15-character string that is not base62 at all.
  assert.equal(ROOM.isValidRoomId('!!!!!!!!!!!!!!!'), false);
  assert.equal(ROOM.isValidRoomId('smith-ossifrag'), false);
  // Every character of the alphabet is acceptable in every position.
  for (const ch of ALPHABET) {
    assert.ok(ROOM.isValidRoomId(ch.repeat(15)), `15 copies of ${ch} should be valid`);
  }
});

test('validation messages name the problem a person can act on', () => {
  assert.equal(ROOM.roomIdError(ROOM.generateRoomId()), null);
  assert.match(ROOM.roomIdError(''), /invitation/);
  assert.match(ROOM.roomIdError('abc'), /exactly 15 characters/);
  assert.match(ROOM.roomIdError('abc'), /this one has 3/);
  assert.match(ROOM.roomIdError('aaaaaaaaaaaaaaa'.replace('a', '-', )), /letters A-Z, a-z and digits 0-9/);
  assert.match(ROOM.roomIdError('-aaaaaaaaaaaaaa'), /letters A-Z, a-z and digits 0-9/);
});

test('parseRoomInput accepts every form a person would paste', () => {
  const id = ROOM.generateRoomId();
  const forms = [
    [id, id],
    [`  ${id}  `, id],
    [`https://meet.example.org/${id}`, id],
    [`https://talk.brave.com/${id}`, id],
    [`https://meet.example.org/${id}?foo=1`, id],
    [`https://meet.example.org/${id}#tile-view`, id],
    [`ziy-talk://${id}`, id],
    [`http://meet.example.org/${id}`, id],
    [`https://meet.example.org/some/room/${id}`, id],
    [`%20${id}%20`, id],
  ];
  for (const [input, expected] of forms) {
    const parsed = ROOM.parseRoomInput(input);
    assert.equal(parsed.error, null, `no error for ${input}`);
    assert.equal(parsed.roomId, expected, `wrong room for ${input}`);
  }
});

test('parseRoomInput rejects what is not a room, with a reason', () => {
  for (const input of ['', '   ', 'nope', 'hello-world', 'https://meet.example.org/nope']) {
    const parsed = ROOM.parseRoomInput(input);
    assert.equal(parsed.roomId, null, `${input} must not produce a room`);
    assert.equal(typeof parsed.error, 'string');
  }
  // A 16-character trailing segment must not be silently truncated.
  const parsed = ROOM.parseRoomInput('https://meet.example.org/aaaaaaaaaaaaaaaa');
  assert.equal(parsed.roomId, null);
  assert.match(parsed.error, /exactly 15 characters/);
});
