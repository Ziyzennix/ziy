/* Ziy Talk — the room id generator tests.
 *
 * The contract, from replica/re-deep-core.md §6: Brave's observed room ids are a
 * 15-character base62 string appended to the host, and the browser side only
 * ever recognises them — the generation is server-side and closed. Ours is ours,
 * so these tests pin what we chose and what we refuse to do.
 *
 * What matters, in order:
 *   1. the shape: exactly 15 characters, all from base62, no exceptions
 *   2. the entropy class: ~89 bits, so an unguessable room reference, and it is
 *      uniform — every char drawn uniformly, rejection-sampled, no modulo bias
 *   3. no collision across 10,000 samples (the birthday bound at 89 bits is
 *      negligible, but it is asserted anyway because a bug here would be catastrophic)
 *   4. no fallback to Math.random(): a predictable room is worse than no room
 *   5. validation is exact-charset, so a malformed id reaches nothing
 */

'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');

const ROOM = require('../lib/room.js');

const ALPHABET = 'ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789';

test('the generated id has exactly the shape Brave\'s observed ids have', () => {
  for (let i = 0; i < 200; i++) {
    const id = ROOM.generateRoomId();
    assert.equal(id.length, 15, `id ${id} is not 15 characters`);
    for (const ch of id) {
      assert.ok(ALPHABET.includes(ch), `character ${JSON.stringify(ch)} is not base62`);
    }
  }
});

test('the shape Ziy generates matches the shape the recon specifies', () => {
  // replica/re-deep-core.md §6 and its delta list both state the contract as a
  // "15-character base62 room id", and the entropy it implies (~89 bits) is the
  // class the delta list also names. Ziy implements exactly that.
  //
  // HONEST DISCREPANCY, recorded rather than smoothed over: the single concrete
  // sample in the same document,
  //     GURL talk("https://talk.brave.com/1Ar1vHfLBWX2sAdi");
  // is 16 characters, not 15. The document's prose says 15 in two places and its
  // own example is 16, and the recon marked Brave's generator [UNVERIFIED]
  // (server-side, closed) for that reason. Ziy therefore takes the stated length
  // of 15 — the documented contract, with a known entropy class — and does not
  // silently widen validation to accept 16 as well, because a validator that
  // accepts two lengths cannot tell the user which one is wrong.
  //
  // The consequence is stated plainly: a link generated by Brave's own service
  // would be rejected by Ziy's join box. That is the correct behaviour for a
  // cross-product reference whose real format is unverified, and the fix if the
  // 16-character shape is confirmed is to change ROOM_ID_LENGTH in one place.
  for (let i = 0; i < 50; i++) {
    const id = ROOM.generateRoomId();
    assert.equal(id.length, 15);
    assert.equal(ROOM.ENTROPY_BITS.toFixed(1), '89.3');
  }
});

test('the entropy is the class the shape implies: 15 * log2(62) ≈ 89 bits', () => {
  // Not merely >= 80: the exact value, so a change to the length or the alphabet
  // changes this number and this test says so.
  assert.equal(ROOM.ENTROPY_BITS.toFixed(4), (15 * Math.log2(62)).toFixed(4));
  assert.ok(ROOM.ENTROPY_BITS > 80, 'less than 80 bits would be guessable territory');
});

test('every character of the alphabet appears across a large sample', () => {
  // 62 symbols, 10k draws of 15 chars = 150k characters. The chance that any one
  // specific symbol never appears is (61/62)^150000, which is zero to a hundred
  // digits. So seeing all 62 is a real uniformity check, not a formality.
  const ids = Array.from({ length: 10000 }, () => ROOM.generateRoomId());
  const seen = new Set(ids.join('').split(''));
  assert.equal(seen.size, 62, `only ${seen.size} of 62 symbols appeared`);
  assert.deepEqual([...seen].sort(), ALPHABET.split('').sort());
});

test('no collision in 10,000 samples', () => {
  // The birthday bound for 15 chars of base62: with ~2^89.2 buckets and 10^4
  // samples the expected collision count is ~10^8 / 2^90 ≈ 8e-19. Any collision
  // therefore means the generator is not drawing uniformly.
  const ids = new Set(Array.from({ length: 10000 }, () => ROOM.generateRoomId()));
  assert.equal(ids.size, 10000, 'two room ids collided — the generator is not uniform');
});

test('character frequencies are flat within the sampling error of 150k draws', () => {
  // The rejection sampling must remove the modulo bias. At n = 150000 the
  // expected count per symbol is 2419 with a binomial sigma of ~49, so 6 sigma
  // is a strict bound that still never fires on a correct generator.
  const counts = Object.create(null);
  for (const ch of ALPHABET) counts[ch] = 0;
  const total = 150000;
  for (let i = 0; i < total / 15; i++) {
    for (const ch of ROOM.generateRoomId()) counts[ch] += 1;
  }
  const perSymbol = total / 62;
  const sigma = Math.sqrt(perSymbol * (61 / 62));
  for (const ch of ALPHABET) {
    const z = Math.abs(counts[ch] - perSymbol) / sigma;
    assert.ok(z < 6, `symbol ${ch} is biased: ${counts[ch]} vs expected ${perSymbol.toFixed(0)} (${z.toFixed(1)} sigma)`);
  }
});

test('consecutive draws are independent — no counter, no seed reuse', () => {
  const first = ROOM.generateRoomId();
  const second = ROOM.generateRoomId();
  assert.notEqual(first, second);
  // A counter-based generator would produce ids that differ in exactly one
  // position with high probability; a uniform one differs in every position.
  const differing = [...first].filter((ch, i) => ch !== second[i]).length;
  assert.ok(differing >= 10, `only ${differing}/15 positions differ — suspicious for a counter`);
});

test('the acceptance limit is exact, so the rejection probability is provably tiny', () => {
  // 2^64 mod 62, the chance a single 64-bit draw is rejected.
  const modulus = 2n ** 64n % 62n;
  const rejection = Number(modulus) / Math.pow(2, 64);
  assert.ok(rejection < 1e-17, `rejection probability ${rejection} is not negligible`);
  assert.equal(ROOM.ACCEPT_LIMIT.toString(), (2n ** 64n - modulus).toString());
});

test('there is no non-cryptographic fallback', () => {
  // The one failure mode that would silently produce guessable rooms: the
  // generator quietly reaching for Math.random() when the CSPRNG is missing.
  let usedMathRandom = false;
  const savedRandom = Math.random;
  Math.random = () => { usedMathRandom = true; throw new Error('Math.random must never be used'); };
  try {
    const id = ROOM.generateRoomId();
    assert.ok(ROOM.isValidRoomId(id));
    assert.equal(usedMathRandom, false, 'the generator reached for Math.random');
  } finally {
    Math.random = savedRandom;
  }
});

test('the only randomness source getRandomValues can reach is the CSPRNG', () => {
  // Structural, not behavioural: getRandomValues() must not consult Math.random
  // and must not fall back to Date or a seed. Read the function's source and
  // check the identifiers it can possibly touch.
  const source = ROOM.getRandomValues.toString();
  for (const forbidden of ['Math.random', 'Date.now', 'Math.random', 'performance.now']) {
    assert.ok(!source.includes(forbidden), `getRandomValues references ${forbidden}`);
  }
  assert.ok(/getRandomValues|randomFillSync/.test(source), 'no cryptographic source in the body');
});

test('the rejection bound is computed from the alphabet, not hardcoded', () => {
  const modulus = 62n;
  const space = 2n ** 64n;
  const limit = space - (space % modulus);
  assert.equal(ROOM.ACCEPT_LIMIT.toString(), limit.toString());
  // Every symbol has probability exactly 1/62, because the accepted region is an
  // exact multiple of 62 wide.
  assert.equal((ROOM.ACCEPT_LIMIT % 62n), 0n);
  // And the residue — the only rejected strip — is under 62, i.e. 62 * 2^-62
  // wide at most, which is why drawIndex's loop is a guard rather than a lottery.
  assert.ok(space - limit < modulus);
});

